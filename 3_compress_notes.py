"""
Per-document clinical note compression using vLLM server(s).

Each input row is treated as one independent clinical document and is
summarized into a concise oncology-focused paragraph. This mirrors the
"compress-notes" skill from the onc-data-wrangler plugin, but uses the same
local-vLLM server management pattern as 6_summarize_patients.py so that
multiple servers can be launched (own GPUs) or reused (external URLs).

Multiple vLLM servers can be launched in parallel to increase throughput.
The number of servers is determined by: n_servers = len(gpu_ids) // gpus_per_server.
Prompts are split into batches, and within each batch documents are distributed
across servers round-robin. After each batch completes its inference, a shard
file is written so that interrupted runs can be resumed.

The final output parquet preserves the original input columns and appends the
note-level compression outputs generated by this script.

Examples
--------
# Launch own servers, 1 GPU each on 8 GPUs:
python 3_compress_notes.py \
  --input_parquet ../data/no_phi/all_synthetic_notes.parquet \
  --output_parquet ../data/no_phi/compressed_notes.parquet \
  --shard_dir ../data/no_phi/compressed_note_shards \
  --model openai/gpt-oss-120b \
  --download_dir ~/models \
  --gpu_ids 0,1,2,3,4,5,6,7 \
  --gpus_per_server 1 \
  --max_model_len 25000 \
  --max_tokens 1024 \
  --patient_id_col pseudo_mrn \
  --text_col synthetic_note \
  --max_concurrent_requests 25

# Use existing external servers:
python 3_compress_notes.py \
  --input_parquet ../data/no_phi/all_synthetic_notes.parquet \
  --output_parquet ../data/no_phi/compressed_notes.parquet \
  --shard_dir ../data/no_phi/compressed_note_shards \
  --model openai/gpt-oss-120b \
  --download_dir ~/models \
  --server_urls http://localhost:8000/v1,http://localhost:8001/v1 \
  --max_model_len 25000 \
  --max_tokens 1024
"""

