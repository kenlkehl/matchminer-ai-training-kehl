async def single_inference_request(
    client: AsyncOpenAI,
    row_idx: int,
    prompt: str,
    model: str,
    temperature: float,
    max_tokens: int,
    top_k: int,
    parser_name: str,
    tokenizer,
    top_p: float = 1.0,
    presence_penalty: float = 0.0,
    min_p: float = 0.0,
    repetition_penalty: float = 1.0,
    max_retries: int = 6,
    base_timeout: float = 600.0,
) -> Tuple[int, str, str]:
    """Send a single inference request with retry logic. Returns (row_idx, reasoning, summary)."""
    for attempt in range(max_retries):
        try:
            extra = {
                "top_k": top_k,
                "repetition_penalty": repetition_penalty,
                "skip_special_tokens": False,
            }
            if min_p > 0.0:
                extra["min_p"] = min_p
            response = await asyncio.wait_for(
                client.completions.create(
                    model=model,
                    prompt=prompt,
                    temperature=temperature,
                    max_tokens=max_tokens,
                    top_p=top_p,
                    presence_penalty=presence_penalty,
                    extra_body=extra,
                ),
                timeout=base_timeout,
            )
            raw_text = response.choices[0].text
            reasoning, summary = postprocess_output(raw_text, parser_name, tokenizer)
            summary = normalize_summary(summary)
            return (row_idx, reasoning, summary)

        except asyncio.TimeoutError:
            wait_time = min((2 ** attempt) * 15, 600)
            if attempt < max_retries - 1:
                print(f"  Row {row_idx}: timeout (attempt {attempt + 1}/{max_retries}), retrying in {wait_time}s...")
                await asyncio.sleep(wait_time)
            else:
                print(f"  Row {row_idx}: all retries exhausted (timeout)")
                return (row_idx, "", "ERROR: timeout after all retries")

        except Exception as e:
            wait_time = min((2 ** attempt) * 10, 300)
            if attempt < max_retries - 1:
                print(f"  Row {row_idx}: error '{e}' (attempt {attempt + 1}/{max_retries}), retrying in {wait_time}s...")
                await asyncio.sleep(wait_time)
            else:
                print(f"  Row {row_idx}: all retries exhausted")
                return (row_idx, "", f"ERROR: {e}")

    return (row_idx, "", "ERROR: unexpected retry loop exit")


async def run_inference_on_server(
    client: AsyncOpenAI,
    prompts: List[Tuple[int, str, int]],  # (row_idx, prompt_text, max_tokens)
    model: str,
    temperature: float,
    top_k: int,
    parser_name: str,
    tokenizer,
    top_p: float = 1.0,
    presence_penalty: float = 0.0,
    min_p: float = 0.0,
    repetition_penalty: float = 1.0,
    max_concurrent: int = 16,
    max_retries: int = 6,
    base_timeout: float = 600.0,
    port: int = 8000,
) -> List[Tuple[int, str, str]]:
    """
    Send a list of prompts to one server with bounded concurrency. The caller
    is responsible for splitting work into batches and writing shards; this
    coroutine just blasts the supplied prompts at the server.
    """
    if not prompts:
        return []

    semaphore = asyncio.Semaphore(max_concurrent)

    async def bounded(row_idx: int, prompt: str, prompt_max_tokens: int):
        async with semaphore:
            return await single_inference_request(
                client=client,
                row_idx=row_idx,
                prompt=prompt,
                model=model,
                temperature=temperature,
                max_tokens=prompt_max_tokens,
                top_k=top_k,
                parser_name=parser_name,
                tokenizer=tokenizer,
                top_p=top_p,
                presence_penalty=presence_penalty,
                min_p=min_p,
                repetition_penalty=repetition_penalty,
                max_retries=max_retries,
                base_timeout=base_timeout,
            )

    # Quick health probe before launching the batch
    if not check_server_health(port):
        print(f"  WARNING: server at port {port} health check failed before batch start")

    tasks = [bounded(idx, prompt, mt) for idx, prompt, mt in prompts]
    return await asyncio.gather(*tasks)


