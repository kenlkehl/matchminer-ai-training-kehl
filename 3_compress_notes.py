_shard_pattern = re.compile(r"compressed_shard_(\d+)\.parquet")


def load_existing_shards(shard_dir: str) -> Dict[int, Tuple[str, str]]:
    """Load all existing shards. Returns dict row_idx -> (reasoning, summary)."""
    results: Dict[int, Tuple[str, str]] = {}
    if not os.path.exists(shard_dir):
        return results
    shard_files = sorted(glob.glob(os.path.join(shard_dir, "compressed_shard_*.parquet")))
    for shard_file in shard_files:
        try:
            shard_df = pd.read_parquet(shard_file)
        except Exception as e:
            print(f"  WARNING: could not read shard {shard_file}: {e}")
            continue
        for _, row in shard_df.iterrows():
            row_idx = int(row["row_idx"])
            reasoning = str(row["reasoning"]) if pd.notna(row["reasoning"]) else ""
            summary = str(row["summary"]) if pd.notna(row["summary"]) else ""
            results[row_idx] = (reasoning, summary)
    return results


def next_shard_index(shard_dir: str) -> int:
    """Return the next shard number to write."""
    if not os.path.exists(shard_dir):
        return 0
    shard_files = glob.glob(os.path.join(shard_dir, "compressed_shard_*.parquet"))
    max_idx = -1
    for path in shard_files:
        m = _shard_pattern.match(os.path.basename(path))
        if m:
            max_idx = max(max_idx, int(m.group(1)))
    return max_idx + 1


def save_shard(
    shard_dir: str,
    shard_idx: int,
    results: List[Tuple[int, str, str]],
) -> str:
    """Save a batch of (row_idx, reasoning, summary) tuples as a shard."""
    os.makedirs(shard_dir, exist_ok=True)
    shard_path = os.path.join(shard_dir, f"compressed_shard_{shard_idx:05d}.parquet")
    shard_df = pd.DataFrame(results, columns=["row_idx", "reasoning", "summary"])
    shard_df.to_parquet(shard_path, index=False)
    print(f"Saved shard: {shard_path} ({len(results)} records)")
    return shard_path


